#!/usr/bin/env python3
"""Write fonts/fonts.css for the font files present in fonts/ (copied from ../launch30/node_modules, see FONTS.md)."""
import os, re
HERE = os.path.dirname(os.path.abspath(__file__)); F = os.path.join(HERE, "..", "fonts"); NM = os.path.join(HERE, "..", "..", "launch30", "node_modules")
have = set(os.listdir(F)); out = []
srcs = [("@fontsource-variable/inter/opsz.css", None), ("@fontsource-variable/inter/opsz-italic.css", None),
        ("@fontsource/jetbrains-mono/400.css", None), ("@fontsource/jetbrains-mono/500.css", None)] + [(f"@fontsource/noto-sans-jp/{w}.css", None) for w in (400, 500, 700, 900)]
for rel, _ in srcs:
    css = open(os.path.join(NM, rel), encoding="utf-8").read()
    for block in re.findall(r"@font-face\s*{[^}]*}", css):
        m = re.search(r"url\(\./files/([^)]+\.woff2)\)\s*format\('([^']+)'\)", block)
        if not m or m.group(1) not in have:
            continue
        block = re.sub(r"src:[^;]*;", f"src: url(./{m.group(1)}) format('{m.group(2)}');", block)
        block = block.replace("font-display: swap;", "font-display: block;")
        out.append(block)
open(os.path.join(F, "fonts.css"), "w", encoding="utf-8").write("/* generated by tools/make_fonts_css.py; faces under the SIL Open Font License 1.1 */\n" + "\n".join(out) + "\n")
print(len(out), "faces")
