#!/usr/bin/env python3
"""Write fonts/fonts.css: Inter (variable, Latin and Greek, roman and italic) and every Noto Sans JP subset at 400 and 700.

The Inter files are the ones already in fonts/ (copied from the flagship2 film, the same font versions). The Noto Sans JP
subsets are copied from launch30/node_modules/@fontsource/noto-sans-jp (SIL Open Font License 1.1). Each face keeps its
unicode-range, so a browser loads only the subsets a page needs, from this folder. No font is fetched over the network.
"""
import os, re
HERE = os.path.dirname(os.path.abspath(__file__)); F = os.path.join(HERE, "..", "fonts")
NM = os.path.join(HERE, "..", "..", "launch30", "node_modules", "@fontsource", "noto-sans-jp")
have = set(os.listdir(F))
out = []
# Inter: the faces already present, written as in flagship2 (block display set to block for a deterministic render)
inter = open(os.path.join(F, "fonts.css"), encoding="utf-8").read() if os.path.exists(os.path.join(F, "fonts.css")) else ""
for block in re.findall(r"@font-face\s*{[^}]*}", inter):
    if "Inter Variable" in block:
        out.append(block)
for w in (400, 700):
    css = open(os.path.join(NM, f"{w}.css"), encoding="utf-8").read()
    for block in re.findall(r"@font-face\s*{[^}]*}", css):
        m = re.search(r"url\(\./files/([^)]+\.woff2)\)\s*format\('woff2'\)", block)
        if not m or m.group(1) not in have:
            continue
        block = re.sub(r"src:[^;]*;", f"src: url(./{m.group(1)}) format('woff2');", block)
        block = block.replace("font-display: swap;", "font-display: block;")
        out.append(block)
open(os.path.join(F, "fonts.css"), "w", encoding="utf-8").write("/* generated by tools/make_fonts_css.py; faces under the SIL Open Font License 1.1 */\n" + "\n".join(out) + "\n")
print(len(out), "faces")
