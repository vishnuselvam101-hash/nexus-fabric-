#!/usr/bin/env python3
"""Writes data/check-labels.js: the Japanese names the product itself gives its checks (web/i18n.js of the application),
for the check names this job returns (data/en/checks-5.json). Names with no Japanese label keep the machine name.

  python3 tools/build_check_labels.py <path to the application's web/i18n.js>
"""
import json, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.join(HERE, '..')
src = open(sys.argv[1], encoding='utf-8').read()
names = sorted({c['name'] for c in json.load(open(os.path.join(ROOT, 'data', 'en', 'checks-5.json'), encoding='utf-8'))})
found = {}
for m in re.finditer(r"\b([a-z][a-z0-9_]*): \[(null|'[^']*'), '([^']+)'\]", src):
    if m.group(1) in names:
        found[m.group(1)] = m.group(3)
missing = [n for n in names if n not in found]
out = 'window.NF_CHECK_JA = ' + json.dumps(found, ensure_ascii=False, indent=0, sort_keys=True) + ';\n'
open(os.path.join(ROOT, 'data', 'check-labels.js'), 'w', encoding='utf-8').write('// Japanese names of the checks, from the application\'s own interface strings (web/i18n.js). Generated by tools/build_check_labels.py.\n' + out)
print(len(found), 'of', len(names), 'check names have a Japanese label; missing:', missing)
